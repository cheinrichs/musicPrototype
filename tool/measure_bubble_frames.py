#!/usr/bin/env python3
"""Writes lib/ui/components/bubble_frames.dart: where each frame sits on
Cooper's bubble sheets (card 231).

THE MANIFEST IS THE SOURCE OF TRUTH FOR WHERE TO CUT:
assets/images/characters/instruments/SLICE_POINTS.json. Neither sheet slices
on an even grid — even cells cut through the art on both — so the frames are
the columns between the manifest's cut points, never width / frames.

Each frame is then drawn from its own tight box (alpha > 8). The wiggle's
frames drift up to 19 px vertically; Cooper approved that in motion, so each
frame is anchored on its OWN box centre and the drift reads as drawn.

Refuses to write anything if a cut column holds opaque art (alpha >= 128).

Usage (from the repo root):
    python3 -E tool/measure_bubble_frames.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parent.parent
ART = REPO / "assets" / "images" / "ui" / "bubble"
MANIFEST = REPO / "assets" / "images" / "characters" / "instruments" / "SLICE_POINTS.json"
OUT = REPO / "lib" / "ui" / "components" / "bubble_frames.dart"
FAINT = 8
OPAQUE = 128

SHEETS = {
    "burst": "bubble_burst_sheet.png",
    "wiggle": "bubble_wiggle_sheet.png",
    "idle": "bubble_idle.png",
}


def main() -> None:
    manifest = json.loads(MANIFEST.read_text())
    lines = [
        "// GENERATED by tool/measure_bubble_frames.py from the bubble sheets and",
        "// assets/images/characters/instruments/SLICE_POINTS.json. Do not edit:",
        "// re-run the tool. test/ui/bubble_frames_test.dart re-measures it.",
        "",
        "import 'dart:ui';",
        "",
        "/// Each bubble sheet's frames, left to right, as tight boxes in sheet",
        "/// pixels (card 231).",
        "const bubbleFrames = <String, (String, Size, List<Rect>)>{",
    ]
    for name, file in SHEETS.items():
        entry = manifest[file]
        a = np.array(Image.open(ART / file).getchannel("A"))
        h, w = a.shape
        if w != entry["width"]:
            sys.exit(f"{file}: {w} wide, manifest says {entry['width']}")
        cuts = [0, *entry["slices"], w]
        boxes = []
        for i in range(len(cuts) - 1):
            x0, x1 = cuts[i], cuts[i + 1]
            col = a[:, x0:x1]
            if i > 0 and (a[:, x0] >= OPAQUE).any():
                sys.exit(f"{file}: cut {x0} crosses opaque art")
            faint = col > FAINT
            ys = np.flatnonzero(faint.any(axis=1))
            xs = np.flatnonzero(faint.any(axis=0))
            boxes.append((x0 + xs[0], ys[0], xs[-1] - xs[0] + 1, ys[-1] - ys[0] + 1))
        lines.append(f"  '{name}': (")
        lines.append(f"    'assets/images/ui/bubble/{file}',")
        lines.append(f"    Size({w}, {h}),")
        lines.append("    [")
        for (l, t, bw, bh) in boxes:
            lines.append(f"      Rect.fromLTWH({l}, {t}, {bw}, {bh}),")
        lines.append("    ],")
        lines.append("  ),")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    subprocess.run(["dart", "format", str(OUT)], check=True, capture_output=True)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
