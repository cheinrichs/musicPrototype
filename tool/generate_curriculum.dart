// Generates lib/curriculum/curriculum_data.g.dart from the authored CSVs in
// docs/curriculum/ — so the curriculum is type-checked Dart in the app, never
// a CSV parsed on a child's iPad. A malformed row fails HERE, at build time,
// not as a crash at launch.
//
//   dart run tool/generate_curriculum.dart          # write the file
//   dart run tool/generate_curriculum.dart --check  # CI: fail if stale/bad
//
// docs/curriculum/ stays the authored source; never edit the .g.dart.
import 'dart:io';

import 'package:ear_trainer/curriculum/csv_table.dart';
import 'package:ear_trainer/curriculum/curriculum.dart';
import 'package:ear_trainer/models/agency_stage.dart';

const _source = 'docs/curriculum/skill_progression_working.csv';
const _nodesSource = 'docs/curriculum/nodes.csv';
const _out = 'lib/curriculum/curriculum_data.g.dart';

void main(List<String> args) {
  final check = args.contains('--check');
  final String generated;
  try {
    generated = generate(
      File(_source).readAsStringSync(),
      File(_nodesSource).readAsStringSync(),
    );
  } on Object catch (e) {
    stderr.writeln('Curriculum is malformed: $e');
    exit(1);
  }
  final out = File(_out);
  if (check) {
    if (!out.existsSync() || out.readAsStringSync() != generated) {
      stderr.writeln(
        '$_out is out of date with docs/curriculum/. '
        'Run: dart run tool/generate_curriculum.dart',
      );
      exit(1);
    }
    stdout.writeln('Curriculum: generated Dart is current.');
    return;
  }
  out.writeAsStringSync(generated);
  stdout.writeln('Wrote $_out');
}

/// The generated library's source, after validating every row.
String generate(String progressionCsv, String nodesCsv) {
  final nodes = [
    for (final row in parseCsvTable(nodesCsv)) _required(row, 'Node', 'nodes'),
  ];
  if (nodes.toSet().length != nodes.length) {
    throw const FormatException('nodes.csv names a node twice');
  }

  // Every row of the sheet, with no built-game replacement: that happens in
  // the app (curriculum.dart), so the generated data is the sheet as
  // authored — all four tiers, none dropped by rule.
  final rows = parseSkillProgression(progressionCsv);
  final seen = <String>{};
  for (final (i, r) in rows.indexed) {
    final where = 'skill progression row ${i + 2}';
    if (r.skillNode.isEmpty || r.game.isEmpty) {
      throw FormatException('$where: blank Node or Skill');
    }
    if (!nodes.contains(r.skillNode)) {
      throw FormatException(
        '$where: node "${r.skillNode}" is not in nodes.csv',
      );
    }
    if (r.tier < 1) throw FormatException('$where: tier ${r.tier}');
    if (r.minAgency.index > r.maxAgency.index) {
      throw FormatException('$where: MinAgency above MaxAgency');
    }
    if (!seen.add(r.token)) {
      throw FormatException('$where: ${r.token} appears twice');
    }
  }

  String str(String s) =>
      "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
  String agency(AgencyStage a) => 'AgencyStage.${a.name}';

  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_curriculum.dart from '
      'docs/curriculum/. DO NOT EDIT —',
    )
    ..writeln('// edit the CSVs and rerun the generator.')
    ..writeln()
    ..writeln("import '../models/agency_stage.dart';")
    ..writeln("import 'curriculum.dart';")
    ..writeln()
    ..writeln('/// The skill nodes, in authored order.')
    ..writeln('const List<String> skillNodes = [')
    ..writeAll([for (final n in nodes) '  ${str(n)},\n'])
    ..writeln('];')
    ..writeln()
    ..writeln(
      '/// The Skill Progression table as authored (agency remapped onto '
      "the app's",
    )
    ..writeln(
      '/// three levels). The built games\' rows are replaced in '
      'curriculum.dart.',
    )
    ..writeln('const List<GameRequirement> sheetRequirements = [');
  for (final r in rows) {
    b
      ..writeln('  GameRequirement(')
      ..writeln('    skillNode: ${str(r.skillNode)},')
      ..writeln('    game: ${str(r.game)},')
      ..writeln('    tier: ${r.tier},')
      ..writeln('    minAgency: ${agency(r.minAgency)},')
      ..writeln('    maxAgency: ${agency(r.maxAgency)},');
    if (r.sheetPrerequisite.isNotEmpty) {
      b.writeln('    sheetPrerequisite: ${str(r.sheetPrerequisite)},');
    }
    b.writeln('  ),');
  }
  b.writeln('];');
  return b.toString();
}

String _required(Map<String, String> row, String column, String file) {
  final v = row[column];
  if (v == null || v.isEmpty) {
    throw FormatException('$file.csv: a row has no $column');
  }
  return v;
}
