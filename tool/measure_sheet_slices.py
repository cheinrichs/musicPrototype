#!/usr/bin/env python3
"""Writes lib/games/high_low/models/instrument_sheets.dart: where each
variant sits on Cooper's three-variant instrument sheets.

THE MANIFEST IS THE SOURCE OF TRUTH FOR WHERE TO CUT:
assets/images/characters/instruments/SLICE_POINTS.json (measured and
supplied 2026-11-20, kept beside the sheets). A sheet is NEVER cut into
equal thirds: that cuts through the art on 8 of 14 sheets (the three
pianos nearly touch). Each sheet's variants are the columns
[0:x1], [x1:x2], [x2:W].

Within its column, a variant is drawn from its own tight box (alpha > 8),
so a narrow instrument is not drawn small inside a wide column, and its
feet are the box's bottom.

Refuses to write anything if a column edge crosses opaque art (alpha >=
128) or a variant's opaque art touches its column's edge — the clipped-art
failure this replaces.

Usage (from the repo root; re-run whenever a sheet or the manifest
changes, and when Cooper supplies a new sheet, re-measure its cuts first):
    python3 -E tool/measure_sheet_slices.py
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parent.parent
DIR = REPO / "assets" / "images" / "characters" / "instruments"
OUT = REPO / "lib" / "games" / "high_low" / "models" / "instrument_sheets.dart"
FAINT = 8
OPAQUE = 128

# Instrument sheets the app draws, by HighLowInstrument / reward name.
SHEETS = {
    "bells": "bells_x3_variants.png",
    "cello": "cello_x3.png",
    "drum": "drum_x3.png",
    "flute": "flute_x3.png",
    "guitar": "guitar_x3.png",
    "oboe": "oboe_x3.png",
    "piano": "piano_x3.png",
    "trumpet": "trumpet_x3.png",
    "tuba": "tuba_x3.png",
    "violin": "violin_x3.png",
    "xylophone": "xylophone_x3.png",
}


def manifest_key(file: str) -> str:
    return file if file.startswith("bells") else f"instruments_v3/{file}"


def main() -> None:
    manifest = json.loads((DIR / "SLICE_POINTS.json").read_text())
    lines = [
        "// GENERATED by tool/measure_sheet_slices.py from the sheets and",
        "// assets/images/characters/instruments/SLICE_POINTS.json. Do not edit:",
        "// re-run the tool. test/games/high_low/instrument_sheets_test.dart",
        "// re-measures every value from the PNGs.",
        "",
        "import 'high_low_instrument.dart';",
        "",
        "/// Each instrument's sheet: its three variants' boxes, left to right.",
        "const instrumentSheets = <String, InstrumentSheet>{",
    ]
    for name, file in SHEETS.items():
        entry = manifest[manifest_key(file)]
        a = np.array(Image.open(DIR / file).getchannel("A"))
        h, w = a.shape
        if w != entry["width"]:
            sys.exit(f"{file}: {w} wide, manifest says {entry['width']}")
        cuts = [0, *entry["slices"], w]
        regions = []
        for i in range(3):
            x0, x1 = cuts[i], cuts[i + 1]
            col = a[:, x0:x1]
            opaque = col >= OPAQUE
            if opaque[:, 0].any() or opaque[:, -1].any():
                sys.exit(f"{file}: variant {i} has opaque art at its column edge")
            faint = col > FAINT
            ys = np.flatnonzero(faint.any(axis=1))
            xs = np.flatnonzero(faint.any(axis=0))
            regions.append((x0 + xs[0], ys[0], xs[-1] - xs[0] + 1, ys[-1] - ys[0] + 1))
        lines.append(f"  '{name}': InstrumentSheet(")
        lines.append(f"    'assets/images/characters/instruments/{file}',")
        lines.append(f"    width: {w},")
        lines.append(f"    height: {h},")
        lines.append(f"    cuts: [{', '.join(str(c) for c in entry['slices'])}],")
        lines.append("    boxes: [")
        for (l, t, bw, bh) in regions:
            lines.append(f"      ({l}, {t}, {bw}, {bh}),")
        lines.append("    ],")
        lines.append("  ),")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    subprocess.run(["dart", "format", str(OUT)], check=True, capture_output=True)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
